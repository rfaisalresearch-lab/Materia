def prop_block(props):
    out = {}
    for key, (value, unit, conditions, source) in props.items():
        entry = {"value": value, "unit": unit}
        if conditions:
            entry["conditions"] = conditions
        entry["source"] = source
        if source == "calculated":
            entry["origin"] = "calculated"
            entry["source"] = "derived from the lattice parameters in this file"
        out[key] = entry
    return out


def main():
    for m in MATERIALS:
        lattice = {"a": m["a"], "unit": "A", "system": m["system"],
                   "temperature_K": 300, "source": m["lattice_source"]}
        if m["c"] is not None:
            lattice["c"] = m["c"]
        doc = {
            "schema_version": "1.0",
            "id": m["id"], "name": m["name"], "formula": m["formula"],
            "aliases": m["aliases"], "category": m["category"],
            "structure": {
                "prototype": m["prototype"],
                "space_group": {"number": m["sg"][0], "symbol": m["sg"][1]},
                "lattice": lattice,
                "basis": m["basis"],
            },
            "orientations": m["orientations"],
            "terminations": [{
                "id": "ideal-bulk", "orientation": m["orientations"][0],
                "description": "Ideal bulk truncation with no reconstruction applied.",
                "implemented": True,
            }],
            "reconstructions": [],
            "properties": prop_block(m["props"]),
            "recommended_models": m["models"],
            "references": sorted({v[3] for v in m["props"].values()} | {m["lattice_source"]}),
            "license": "CC0-1.0",
            "provenance_note": (
                "Generated by tools/gen_crystal_materials.py; basis expanded from the published "
                "Wyckoff parameters of the cited structure determination. "
                + m.get("note", "")
            ).strip(),
        }
        path = os.path.join(OUT, f"{doc['id']}.json")
        with open(path, "w") as fh:
            json.dump(doc, fh, indent=2)
            fh.write("\n")
        print("wrote", os.path.relpath(path), f"({len(doc['structure']['basis'])} basis sites)")


if __name__ == "__main__":
    main()
