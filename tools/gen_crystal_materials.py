OUT = os.path.join(os.path.dirname(__file__), "..", "materia", "materials", "library")
T3 = 1.0 / 3.0
T23 = 2.0 / 3.0


def r(x):
    return round(float(x) % 1.0, 7)


def diamond_basis(sym_a, sym_b):
    """Diamond-cubic / zinc-blende conventional cell (8 sites)."""
    fcc = [(0, 0, 0), (0, .5, .5), (.5, 0, .5), (.5, .5, 0)]
    out = []
    for f in fcc:
        out.append({"element": sym_a, "fractional": [r(v) for v in f],
                    "label": f"{sym_a}(a)", "wyckoff": "4a"})
    for f in fcc:
        out.append({"element": sym_b,
                    "fractional": [r(v + .25) for v in f],
                    "label": f"{sym_b}(c)", "wyckoff": "4c"})
    return out


def wurtzite_basis(cation, anion, u):
    return [
        {"element": cation, "fractional": [r(T3), r(T23), 0.0], "label": f"{cation}(1)", "wyckoff": "2b"},
        {"element": cation, "fractional": [r(T23), r(T3), 0.5], "label": f"{cation}(2)", "wyckoff": "2b"},
        {"element": anion, "fractional": [r(T3), r(T23), r(u)], "label": f"{anion}(1)", "wyckoff": "2b"},
        {"element": anion, "fractional": [r(T23), r(T3), r(u + .5)], "label": f"{anion}(2)", "wyckoff": "2b"},
    ]


def hbn_basis():
    return [
        {"element": "B", "fractional": [r(T3), r(T23), 0.25], "label": "B", "wyckoff": "2c"},
        {"element": "B", "fractional": [r(T23), r(T3), 0.75], "label": "B", "wyckoff": "2c"},
        {"element": "N", "fractional": [r(T23), r(T3), 0.25], "label": "N", "wyckoff": "2d"},
        {"element": "N", "fractional": [r(T3), r(T23), 0.75], "label": "N", "wyckoff": "2d"},
    ]


def tmd_2h_basis(metal, chalc, z):
    """2H-MX2 (P6_3/mmc): M on 2c, X on 4f with internal parameter z."""
    return [
        {"element": metal, "fractional": [r(T3), r(T23), 0.25], "label": metal, "wyckoff": "2c"},
        {"element": metal, "fractional": [r(T23), r(T3), 0.75], "label": metal, "wyckoff": "2c"},
        {"element": chalc, "fractional": [r(T3), r(T23), r(z)], "label": chalc, "wyckoff": "4f"},
        {"element": chalc, "fractional": [r(T23), r(T3), r(z + .5)], "label": chalc, "wyckoff": "4f"},
        {"element": chalc, "fractional": [r(T23), r(T3), r(-z)], "label": chalc, "wyckoff": "4f"},
        {"element": chalc, "fractional": [r(T3), r(T23), r(-z + .5)], "label": chalc, "wyckoff": "4f"},
    ]


def corundum_basis(z_al, x_o):
    """alpha-Al2O3, R-3c (#167), hexagonal setting: Al on 12c, O on 18e."""
    centering = [(0, 0, 0), (T23, T3, T3), (T3, T23, T23)]
    al_core = [(0, 0, z_al), (0, 0, -z_al), (0, 0, z_al + .5), (0, 0, -z_al + .5)]
    o_core = [(x_o, 0, .25), (0, x_o, .25), (-x_o, -x_o, .25),
              (-x_o, 0, .75), (0, -x_o, .75), (x_o, x_o, .75)]
    out = []
    for c in centering:
        for p in al_core:
            out.append({"element": "Al", "fractional": [r(p[i] + c[i]) for i in range(3)],
                        "label": "Al", "wyckoff": "12c"})
    for c in centering:
        for p in o_core:
            out.append({"element": "O", "fractional": [r(p[i] + c[i]) for i in range(3)],
                        "label": "O", "wyckoff": "18e"})
    return out


def quartz_basis(x_si, x_o, y_o, z_o):
    """alpha-SiO2 in the P3_2 21 setting (#154): Si on 3a, O on 6c.

    The general positions are those generated by the 3_2 screw
    (x, y, z) -> (-y, x-y, z+2/3) and the two-fold axis (x, y, z) -> (y, x, -z).
    The origin convention matters: with Si on 3a at z = 2/3 the oxygen z from
    Levien et al. must be taken as 0.7858, not 0.1191. The resulting cell is
    checked against the published Si-O and O-O distances in
    tests/validation/test_physical_validation.py.
    """
    si = [(x_si, 0.0, T23), (0.0, x_si, T3), (-x_si, -x_si, 0.0)]
    x, y, z = x_o, y_o, z_o
    o = [(x, y, z), (-y, x - y, z + T23), (-x + y, -x, z + T3),
         (y, x, -z), (-x, -x + y, -z + T23), (x - y, -y, -z + T3)]
    out = [{"element": "Si", "fractional": [r(v) for v in p], "label": "Si",
            "wyckoff": "3a"} for p in si]
    out += [{"element": "O", "fractional": [r(v) for v in p], "label": "O",
             "wyckoff": "6c"} for p in o]
    return out


