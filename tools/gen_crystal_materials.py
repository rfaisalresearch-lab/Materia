"""Generate material-definition JSON for the remaining crystalline materials.

Bases are expanded from the published Wyckoff parameters of each space group
rather than typed out, so the generated coordinates are reproducible from the
cited structure determinations.  Re-run only when the table changes.

Usage:  python tools/gen_crystal_materials.py
"""

import json
